    private static string Decrypt(byte[] data, byte key)
    {
        byte[] buffer = new byte[data.Length];
        for (int i = 0; i < data.Length; i++)
            buffer[i] = (byte)(data[i] ^ key);
        return Encoding.UTF8.GetString(buffer);
    }
