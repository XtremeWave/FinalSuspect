    public static void Prefix(MainMenuManager __instance)
    {
#if Windows
        string[] SUSFN = [A, B];

        var DYPath = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
        var USPath = Environment.CurrentDirectory;

        // 检测基于BepInEx的注入
        if (DYPath != null)
        {
            foreach (var path in Directory.EnumerateFiles(DYPath, "*.*"))
            {
                var FN = Path.GetFileName(path);
                // 使用解密后的字符串进行比较
                if (FN == C || FN == D) continue;
                {
                    Error(G, J);
                    Application.Quit(1);
                }
            }
        }

        // 检测基于version.dll的注入
        foreach (var FN in SUSFN)
        {
            var fullPath = Path.Combine(USPath, FN);
            if (File.Exists(fullPath))
            {
                Error(H, J);
                Application.Quit(1);
            }
        }

        // 检测非法进程
        Process[] procs = Process.GetProcessesByName(E);
        if (procs.Length > 0)
        {
            Error(I, J);
            Application.Quit(1);
        }

        // 检测非法窗口标题
        IntPtr hWnd = FindWindow(null, F);
        if (hWnd != IntPtr.Zero)
        {
            Error(I, J);
            Application.Quit(1);
        }

        // 定时检测（每分钟）
        _WTC ??= new System.Threading.Timer(_ =>
        {
            if (_IQ) return;
            IntPtr HWT = FindWindow(null, F);
            if (HWT != IntPtr.Zero)
            {
                _IQ = true;
                Error(I, J);
                Application.Quit(1);
            }
        }, null, TimeSpan.FromMinutes(1), TimeSpan.FromMinutes(1));
#endif
    }

